/**
 * Regenerates cross-language test fixtures consumed by the Rust crates.
 *   node scripts/dev/gen-fixtures.ts
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { PublicKey, buildAirdropTree, toHex } from "@float-community/sdk";

const wallets = [1, 2, 3, 4].map((b) => new PublicKey(new Uint8Array(32).fill(b)));
const tree = buildAirdropTree(2n, wallets.map((w, i) => ({ wallet: w, amount: BigInt((i + 1) * 1_000_000) })));

const out = {
  description: "Generated by scripts/dev/gen-fixtures.ts — do not edit by hand",
  roundId: 2,
  root: toHex(tree.root),
  wallet0: toHex(wallets[0]!.bytes),
  amount0: 1000000,
  leaf0: toHex(tree.leaves[0]!.leaf),
  proof0: tree.leaves[0]!.proof.map(toHex),
};
const path = fileURLToPath(new URL("../../crates/float-core/tests/fixtures/airdrop-merkle.json", import.meta.url));
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${path}`);
